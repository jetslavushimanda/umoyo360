export function getFoodById(id) {
  return FOODS_DATABASE.find(f => f.id === id);
}

export function getFoodsByCategory(category) {
  return FOODS_DATABASE.filter(f => f.category === category);
}

export function getCategories() {
  return [...new Set(FOODS_DATABASE.map(f => f.category))];
}

export function getForbiddenFoodsForCondition(conditionId) {
  return FOODS_DATABASE.filter(f => f.forbiddenFor.includes(conditionId));
}

export function getRecommendedFoodsForCondition(conditionId) {
  return FOODS_DATABASE.filter(f => f.recommendedFor.includes(conditionId));
}
